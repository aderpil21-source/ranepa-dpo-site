const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context=vm.createContext({Intl,Date});
vm.runInContext(fs.readFileSync('students-live.js','utf8'),context);
const {state,merge,interval}=context.StudentLiveLecture;
const lesson={id:'one',date:'30.10.2026',time:'18:00–19:30',subject:'Тема',program:'Программа'};
const at=s=>state([lesson],new Date(s));
assert.equal(at('2026-10-30T15:59:59.000Z').active.length,0);
assert.equal(at('2026-10-30T16:00:00.000Z').active.length,1);
assert.equal(at('2026-10-30T17:29:59.999Z').active.length,1);
assert.equal(at('2026-10-30T17:30:00.000Z').active.length,0);
assert.equal(at('2026-10-29T16:30:00Z').active.length,0);
assert.equal(at('2026-10-30T15:59:59.500Z').delay,500);
assert.equal(interval({...lesson,time:'14:00'}),null);
assert.equal(interval({...lesson,time:'25:00–26:00'}),null);
assert.equal(interval({...lesson,date:'31.02.2026'}),null);
assert.equal(state([{...lesson,date:'29.10.2026 - 31.10.2026'}],new Date('2026-10-30T16:00:00Z')).active.length,1);
const key='schedule:'+['one',lesson.date,lesson.time,lesson.subject].map(encodeURIComponent).join('|');
for(const patch of [{active:false},{archived:true},{cancelled:true}])assert.equal(merge([lesson],{customSchedules:[{sourceKey:key,...patch}]}).length,0);
assert.equal(merge([lesson],{visibility:{[key]:false}}).length,0);
assert.equal(merge([lesson],{customSchedules:[{sourceKey:key,replacement:true,time:'19:00–20:00'}]})[0].replacement,true);
assert.equal(state(merge([lesson],{customSchedules:[{sourceKey:key,time:'19:00–20:00'}]}),new Date('2026-10-30T16:00:00Z')).active.length,0);
console.log('Live lecture boundaries, Kaliningrad time, invalid data, overrides and visibility passed.');
